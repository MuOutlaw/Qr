/** جميع المدن المسطحة */
export const ALL_CITIES: string[] = SAUDI_REGIONS.flatMap((r) => r.cities);

/** الحصول على مدن منطقة معينة */
export function getCitiesByRegion(regionName: string): string[] {
  return SAUDI_REGIONS.find((r) => r.name === regionName)?.cities ?? [];
}

/** الحصول على اسم المنطقة من اسم المدينة */
export function getRegionByCity(cityName: string): string | undefined {
  return SAUDI_REGIONS.find((r) => r.cities.includes(cityName))?.name;
}
